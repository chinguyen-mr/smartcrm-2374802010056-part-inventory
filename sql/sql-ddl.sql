-- ================================================================
-- DDL chính thức cho BT2 – Smart CRM Luồng L5: Quản lý tồn kho linh kiện
-- Schema đã được chốt theo ERD (docs/diagrams/erd.drawio)
-- Cơ sở dữ liệu: PostgreSQL 15+
-- 7 bảng: employee, service_center, part, part_stock,
--         ticket_ref, ticket_part, part_transaction
-- ================================================================

-- 1. Danh mục trung tâm bảo hành
CREATE TABLE service_center (
    center_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    center_code VARCHAR(20)  NOT NULL UNIQUE,
    center_name VARCHAR(120) NOT NULL
);

-- 2. Nhân viên (KTV / Quản lý trung tâm)
--    Dữ liệu gốc: technicians.csv (38 nhân viên thuộc 6 trung tâm).
--    L5 sử dụng bảng này để mô hình hóa tác nhân thao tác kho.
--    Xác thực thực tế đi qua JWT; bảng employee phục vụ ERD đầy đủ
--    và tra cứu thông tin nhân viên khi cần.
CREATE TABLE employee (
    employee_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_code  VARCHAR(20)  NOT NULL UNIQUE,
    full_name      VARCHAR(120) NOT NULL,
    center_id      BIGINT       NOT NULL REFERENCES service_center(center_id),
    role           VARCHAR(30)  NOT NULL DEFAULT 'KTV'
                   CHECK (role IN ('KTV', 'QUAN_LY_TRUNG_TAM')),
    is_active      BOOLEAN      NOT NULL DEFAULT TRUE
);

-- 3. Danh mục linh kiện thay thế
CREATE TABLE part (
    part_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    part_code  VARCHAR(30)   NOT NULL UNIQUE,
    part_name  VARCHAR(120)  NOT NULL,
    unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0)
);

-- 4. Số dư tồn kho theo cặp trung tâm / linh kiện
--    Mỗi cặp có tối đa một dòng; tồn không âm.
--    min_threshold NOT NULL: khi chưa cấu hình, giá trị mặc định là 0
--    (không cảnh báo cho đến khi QLTT đặt ngưỡng thực tế).
CREATE TABLE part_stock (
    center_id     BIGINT  NOT NULL REFERENCES service_center(center_id),
    part_id       BIGINT  NOT NULL REFERENCES part(part_id),
    quantity      INTEGER NOT NULL DEFAULT 0 CHECK (quantity >= 0),
    min_threshold INTEGER NOT NULL DEFAULT 0 CHECK (min_threshold >= 0),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (center_id, part_id)
);

-- 5. Tham chiếu phiếu bảo hành (lưu nội bộ để kiểm tra trung tâm)
--    ticket_code là mã do hệ thống phiếu ngoài cấp; L5 chỉ lưu tham chiếu.
CREATE TABLE ticket_ref (
    ticket_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    center_id   BIGINT      NOT NULL REFERENCES service_center(center_id),
    ticket_code VARCHAR(20) NOT NULL UNIQUE,
    status      VARCHAR(30) NOT NULL DEFAULT 'DANG_XU_LY'
);

-- 6. Liên kết phiếu – linh kiện (một phiếu có thể dùng nhiều linh kiện)
--    transaction_id được điền sau khi giao dịch xuất được ghi thành công.
CREATE TABLE ticket_part (
    ticket_part_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id      BIGINT NOT NULL REFERENCES ticket_ref(ticket_id),
    part_id        BIGINT NOT NULL REFERENCES part(part_id),
    transaction_id BIGINT,               -- FK được thêm sau (xem ALTER bên dưới)
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 7. Sổ lịch sử nhập / xuất (bất biến theo QT-13)
--    Giao dịch XUAT phải có ticket_part_id; NHAP thì không.
CREATE TABLE part_transaction (
    transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    center_id      BIGINT      NOT NULL REFERENCES service_center(center_id),
    part_id        BIGINT      NOT NULL REFERENCES part(part_id),
    ticket_part_id BIGINT      REFERENCES ticket_part(ticket_part_id),
    type           VARCHAR(10) NOT NULL CHECK (type IN ('NHAP', 'XUAT')),
    quantity       INTEGER     NOT NULL CHECK (quantity > 0),
    occurred_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    reference      VARCHAR(80),
    CHECK (
        (type = 'NHAP' AND ticket_part_id IS NULL)
        OR
        (type = 'XUAT' AND ticket_part_id IS NOT NULL)
    )
);

-- Khóa ngoại vòng: ticket_part.transaction_id → part_transaction.transaction_id
-- Được khai báo sau khi cả hai bảng đã tạo xong.
ALTER TABLE ticket_part
    ADD CONSTRAINT fk_ticket_part_transaction
    FOREIGN KEY (transaction_id) REFERENCES part_transaction(transaction_id);

-- ================================================================
-- Index hỗ trợ các truy vấn nghiệp vụ chính
-- ================================================================

-- Tra cứu nhân viên theo trung tâm (phân quyền QT-14)
CREATE INDEX idx_employee_center
    ON employee (center_id);

-- Kiểm tra cảnh báo tồn dưới ngưỡng (UC4, UC5)
CREATE INDEX idx_part_stock_alert
    ON part_stock (center_id, quantity, min_threshold);

-- Tra cứu lịch sử theo trung tâm / linh kiện / thời gian (UC7)
CREATE INDEX idx_part_transaction_history
    ON part_transaction (center_id, part_id, occurred_at DESC);

-- Tra cứu giao dịch theo phiếu (UC8)
CREATE INDEX idx_part_transaction_ticket_part
    ON part_transaction (ticket_part_id)
    WHERE ticket_part_id IS NOT NULL;

-- ================================================================
-- Ghi chú xử lý đồng thời (NFR3)
-- ================================================================
-- Khi xuất kho, service phải:
--   1. Mở transaction.
--   2. Khóa dòng tồn bằng SELECT ... FOR UPDATE.
--   3. Kiểm tra quantity >= số lượng yêu cầu.
--   4. Chèn ticket_part (nếu chưa có).
--   5. Chèn part_transaction loại XUAT.
--   6. Cập nhật ticket_part.transaction_id.
--   7. Cập nhật part_stock.quantity và updated_at.
--   8. COMMIT. Bất kỳ lỗi nào phải ROLLBACK toàn bộ.
